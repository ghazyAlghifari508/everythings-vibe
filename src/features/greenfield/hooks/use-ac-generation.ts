"use client";

import { useRouter } from "@tanstack/react-router";
import { useCallback, useEffect, useRef, useState } from "react";
import { syncPaymentStatus } from "@/app/actions/payment";
import { saveAcContent } from "@/features/greenfield/services/ac-save";
import { consumeAcStream } from "@/features/greenfield/services/ac-stream";
import {
	isBackgroundGeneration,
	isStaleCompletedLoader,
	resolveInitialGenerating,
} from "@/features/greenfield/utils/generation-recovery";
import {
	GENERATION_STATUS_POLL_INTERVAL_MS,
	GUARD_WAIT_MS,
} from "@/lib/constants";
import {
	consumeResumeIntent,
	consumeSuppressAutoGen,
} from "@/lib/prompt-handoff";
import { useChatStore, useUIStore } from "@/store";
import type { Plan } from "@/types/database";

// ponytail: module-level in-flight guard. StrictMode's phantom unmount->remount
// aborts the first fetch but the remount fires a second generate before the
// server frees its claim â€” dedupe at module scope so both mounts share one
// generation per project instead of racing two. Keyed by the owning controller
// so an aborted older request's cleanup can never release a newer guard.
const inFlightAcProjects = new Map<string, AbortController>();

/** Release the guard only when this request still owns it. */
function releaseAcGuard(projectId: string, owner: AbortController) {
	if (inFlightAcProjects.get(projectId) === owner) {
		inFlightAcProjects.delete(projectId);
	}
}

interface UseAcGenerationParams {
	projectId: string;
	plan: Plan;
	acStatus?: string | null;
	latestPrdContent?: string;
	latestAcContent?: string | null;
	searchStr: string;
	navigate: (opts: { to: "."; search: object; replace: boolean }) => void;
}

/**
 * Owns Acceptance Criteria generation: the SSE stream, save-recovery, the
 * stale-loader reconciler, auto-generate, and post-payment auto-resume.
 */
export function useAcGeneration({
	projectId,
	plan,
	acStatus,
	latestPrdContent,
	latestAcContent,
	searchStr,
	navigate,
}: UseAcGenerationParams) {
	const router = useRouter();
	const showToast = useUIStore((s) => s.showToast);
	const setGeneratingAC = useChatStore((s) => s.setGeneratingAC);
	const setCreditsExhausted = useChatStore((s) => s.setCreditsExhausted);

	// Loader props are the first frame: a finished AC never paints a spinner.
	const [isGenerating, setIsGenerating] = useState(() =>
		resolveInitialGenerating(
			Boolean(latestPrdContent),
			acStatus,
			Boolean(latestAcContent),
		),
	);
	const [streamingContent, setStreamingContent] = useState<string>("");
	const [thinkingText, setThinkingText] = useState("");
	const [hasError, setHasError] = useState(false);
	const [saveFailed, setSaveFailed] = useState(false);
	const [isRetrySaving, setIsRetrySaving] = useState(false);
	const [localAcContent, setLocalAcContent] = useState<string | null>(
		latestAcContent || null,
	);
	const hasAutoGenerated = useRef(false);
	const abortRef = useRef<AbortController | null>(null);
	const contentRef = useRef("");

	// Sync loader latestAcContent to local optimistic state.
	// Keep optimistic content (contentRef.current) during invalidate gap so
	// post-done doesn't flash the empty placeholder.
	useEffect(() => {
		if (latestAcContent) {
			setLocalAcContent(latestAcContent);
		} else if (!contentRef.current) {
			setLocalAcContent(null);
		}
	}, [latestAcContent]);

	const handleRetrySave = useCallback(async () => {
		setIsRetrySaving(true);
		try {
			await saveAcContent(projectId, contentRef.current);
			setSaveFailed(false);
			setHasError(false);
			router.invalidate();
			showToast("AC berhasil disimpan!", "success");
		} catch (error: unknown) {
			showToast(
				error instanceof Error ? error.message : "Gagal menyimpan AC",
				"error",
			);
		} finally {
			setIsRetrySaving(false);
		}
	}, [projectId, showToast, router]);

	const handleGenerate = useCallback(async () => {
		if (!latestPrdContent) {
			showToast("PRD belum tersedia. Generate PRD terlebih dahulu.", "error");
			return;
		}
		// StrictMode remount fires while the phantom attempt is still settling
		// (its abort lands within ms). Wait briefly for the guard to free up so
		// the real retry proceeds; a genuine duplicate (double-click) times out
		// silently instead of stacking a second request.
		if (inFlightAcProjects.has(projectId)) {
			const deadline = Date.now() + GUARD_WAIT_MS;
			while (inFlightAcProjects.has(projectId) && Date.now() < deadline) {
				await new Promise((r) => setTimeout(r, 50));
			}
			if (inFlightAcProjects.has(projectId)) return;
		}

		abortRef.current?.abort();
		const controller = new AbortController();
		abortRef.current = controller;
		// Acquire the guard keyed by this controller â€” only this request can
		// release it, so an aborted older stream can't free a newer one's slot.
		inFlightAcProjects.set(projectId, controller);
		setIsGenerating(true);
		setGeneratingAC(true);
		setStreamingContent("");
		contentRef.current = "";
		setHasError(false);
		setSaveFailed(false);

		try {
			const response = await fetch("/api/ac/generate", {
				method: "POST",
				headers: { "Content-Type": "application/json" },
				body: JSON.stringify({
					projectId,
				}),
				signal: controller.signal,
			});
			if (!response.ok) {
				const error = await response.json().catch(() => ({}));
				if (response.status === 403) {
					if (error.code === "UPGRADE_REQUIRED") {
						showToast(
							"Generate AC hanya tersedia di paket Pro dan Hengker.",
							"error",
						);
					} else {
						setCreditsExhausted({
							stage: "ac",
							message: error.error || "Kredit habis.",
						});
					}
					setIsGenerating(false);
					setGeneratingAC(false);
					return;
				}
				if (response.status === 409) {
					// Release our own guard slot (we own it), then check whether
					// any *other* live request still owns a generation. Owner
					// alive (double-click) â†’ stay silent, their UI is streaming.
					// No owner (StrictMode phantom aborted it) â†’ the claim was
					// stale; paint the retryable error state instead of a
					// fake-loading dead end.
					releaseAcGuard(projectId, controller);
					if (!inFlightAcProjects.has(projectId)) {
						setHasError(true);
						showToast(
							"Sesi generate sebelumnya terputus. Klik Coba Lagi.",
							"error",
						);
					}
					setIsGenerating(false);
					setGeneratingAC(false);
					return;
				}
				throw new Error(error.error || "Failed to generate AC");
			}
			let receivedTerminalEvent = false;
			// The shared parser flushes the trailing buffer so a final done/error
			// frame without a newline is never dropped, and stops the moment a
			// terminal event arrives so nothing after it can overwrite the result.
			receivedTerminalEvent = await consumeAcStream(response.body, {
				onThinking: (content) => setThinkingText((prev) => prev + content),
				// A failed upstream attempt already streamed reasoning; the
				// retry starts fresh instead of appending a duplicate.
				onThinkingReset: () => setThinkingText(""),
				onDelta: (content) => {
					// Clear unconditionally â€” reading the stale render-time
					// `thinkingText` here left the panel visible after the first
					// token arrived. React bails out when already empty.
					setThinkingText("");
					contentRef.current += content;
					setStreamingContent((prev) => prev + content);
				},
				onDone: () => {
					// Optimistic: tampilkan streamingContent langsung tanpa nunggu loader
					setLocalAcContent(contentRef.current);
					router.invalidate();
					showToast("Acceptance Criteria berhasil digenerate!", "success");
					setIsGenerating(false);
					setGeneratingAC(false);
				},
				onError: (message) => {
					setIsGenerating(false);
					setGeneratingAC(false);
					// Content already streamed but the DB save (Phase 2) failed - offer
					// recovery instead of the generic error state (PRD US-2, AC-2.1/2.2).
					if (contentRef.current.length > 0) {
						setSaveFailed(true);
					} else {
						setHasError(true);
					}
					showToast(message || "Gagal generate AC", "error");
				},
			});
			// Stream closed without a done/error event (connection dropped mid-stream) -
			// content is silently truncated, so surface it instead of leaving no signal.
			if (!receivedTerminalEvent) {
				if (contentRef.current.length > 0) setSaveFailed(true);
				else setHasError(true);
			}
			setIsGenerating(false);
			setGeneratingAC(false);
		} catch (error: unknown) {
			const isAbort =
				(error instanceof DOMException || error instanceof Error) &&
				error.name === "AbortError";
			if (isAbort) {
				// A newer handleGenerate call already superseded this one (see
				// abortRef.current?.abort() above), or unmount cleared the ref.
				// Either way that flow owns isGenerating/error state now.
				if (abortRef.current !== controller) {
					// Abort came from unmount/route transition, not a newer
					// handleGenerate taking over (abortRef was cleared). Surface a
					// retryable error so the user isn't left at a dead-end - without
					// the misleading "timeout" toast this path used to show.
					if (abortRef.current === null) {
						setHasError(true);
						setIsGenerating(false);
						setGeneratingAC(false);
					}
					return;
				}
				showToast(
					"Generate AC dibatalkan (timeout). Klik Generate ulang.",
					"error",
				);
				setHasError(true);
				setIsGenerating(false);
				setGeneratingAC(false);
				return;
			}
			console.error("Generate AC error:", error);
			const msg = error instanceof Error ? error.message : "Gagal generate AC";
			showToast(msg, "error");
			setHasError(true);
			setIsGenerating(false);
			setGeneratingAC(false);
		} finally {
			releaseAcGuard(projectId, controller);
		}
	}, [
		projectId,
		latestPrdContent,
		showToast,
		router,
		setGeneratingAC,
		setCreditsExhausted,
	]);

	// Sync server acStatus into store so navbar "Generate Task" stays disabled on refresh (Zustand is in-memory only)
	useEffect(() => {
		setGeneratingAC(acStatus === "generating");
	}, [acStatus, setGeneratingAC]);
	// Recovery reconciler: navigation unmounts this view and drops local
	// state, while the server keeps generating. Completed-but-empty loader
	// rows are stale cache, invalidate once to pull the saved AC. A still-live
	// generation (or a sibling stream owned by a double-mount) revalidates the
	// loader on an interval; the loader is the single source of truth and the
	// effect stops the moment content lands.
	useEffect(() => {
		const hasContent = Boolean(latestAcContent);
		const staleCompleted = isStaleCompletedLoader(acStatus, hasContent);
		const siblingLive = inFlightAcProjects.has(projectId) && !hasContent;
		const backgroundLive = isBackgroundGeneration(acStatus, hasContent);
		if (!staleCompleted && !backgroundLive && !siblingLive) return;
		let cancelled = false;
		if (staleCompleted) {
			void router.invalidate();
			return;
		}
		setIsGenerating(true);
		const timer = setInterval(() => {
			if (cancelled) return;
			void router.invalidate();
		}, GENERATION_STATUS_POLL_INTERVAL_MS);
		return () => {
			cancelled = true;
			clearInterval(timer);
		};
	}, [acStatus, latestAcContent, projectId, router]);
	// Auto-generate AC on first visit
	const handleGenerateRef = useRef(handleGenerate);
	handleGenerateRef.current = handleGenerate;

	useEffect(() => {
		if (plan === "free") return; // jangan auto-generate, tampilkan paywall
		if (
			!latestPrdContent ||
			latestAcContent ||
			acStatus === "completed" ||
			acStatus === "generating" ||
			hasAutoGenerated.current
		)
			return;
		// Suppress auto-generate when navigating from History (user must click explicitly)
		if (consumeSuppressAutoGen(projectId)) return;
		hasAutoGenerated.current = true;
		handleGenerateRef.current();
		// ponytail: auto-gen once per mount; ref guard prevents re-run when handleGenerate ref changes
	}, [acStatus, latestPrdContent, latestAcContent, projectId, plan]);

	// Auto-resume AC generation after payment return.
	// Keyed by the raw search string + a per-orderId guard: `new
	// URLSearchParams(searchStr)` is a fresh object every render, and
	// handleGenerate changes identity mid-generation, so without this the
	// resume flow could fire duplicate sync/generate calls while the
	// Midtrans query params are still in the URL.
	const resumedAcPaymentsRef = useRef<Set<string>>(new Set());
	useEffect(() => {
		const params = new URLSearchParams(searchStr);
		const orderId = params.get("order_id");
		const payment = params.get("payment");
		if (!orderId || payment !== "success") return;
		if (resumedAcPaymentsRef.current.has(orderId)) return;
		resumedAcPaymentsRef.current.add(orderId);
		(async () => {
			try {
				const res = await syncPaymentStatus({ data: orderId });
				if (!res.success) return;
				const resumedStage = consumeResumeIntent(projectId);
				if (resumedStage === "ac") {
					hasAutoGenerated.current = true;
					handleGenerate();
				}
				// Strip Midtrans query params via TanStack Router to keep history in sync
				navigate({ to: ".", search: {}, replace: true });
			} catch (e) {
				console.error("Auto-resume payment sync failed:", e);
			}
		})();
	}, [searchStr, handleGenerate, navigate, projectId]);

	// Abort in-flight generation only when switching to a different project
	// so stale project data is discarded without killing in-flight streams on
	// component remounts or responsive reflows.
	const previousProjectIdRef = useRef(projectId);
	useEffect(() => {
		if (
			previousProjectIdRef.current &&
			projectId &&
			previousProjectIdRef.current !== projectId
		) {
			abortRef.current?.abort();
			// Clear the ref so the aborted call's catch can tell an unmount abort
			// (ref === null) from a superseded one (ref points at a newer call) -
			// mirroring task-detail.tsx. Also frees the module guard instantly
			// instead of after the rejection settles.
			abortRef.current = null;
			hasAutoGenerated.current = false;
			setGeneratingAC(false);
			// Project switch may reuse this component instance - clear stale save-failure
			// state so a recovery banner/content from the previous project can't leak in.
			setSaveFailed(false);
			setHasError(false);
			setStreamingContent("");
			setLocalAcContent(null);
			contentRef.current = "";
		}
		previousProjectIdRef.current = projectId;
	}, [projectId, setGeneratingAC]);

	return {
		acContent: localAcContent,
		handleGenerate,
		handleRetrySave,
		hasError,
		isGenerating,
		isRetrySaving,
		saveFailed,
		streamingContent,
		thinkingText,
	};
}
