import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { STUDIO_SKILL_MANIFEST } from "./studio-skill-manifest";

const root = new URL("../../../../", import.meta.url);
const output = new URL("./studio-skill-assets.generated.ts", import.meta.url);
const entries: string[] = [];
for (const skill of Object.values(STUDIO_SKILL_MANIFEST)) {
	for (const doc of [
		skill.primaryDocument,
		...skill.referenceDocuments,
		...skill.datasets,
	]) {
		if (!doc) continue;
		const content = readFileSync(new URL(doc.path, root));
		assert.ok(content.length > 0, `Empty skill asset: ${doc.path}`);
		assert.equal(
			content.length,
			doc.sizeBytes,
			`Skill asset size mismatch: ${doc.path}`,
		);
		assert.equal(
			createHash("sha256").update(content).digest("hex"),
			doc.sha256,
			`Skill asset integrity mismatch: ${doc.path}`,
		);
		entries.push(
			`${JSON.stringify(doc.path)}: ${JSON.stringify(content.toString("utf8"))},`,
		);
	}
}
const generated = `// Generated by studio-skill-assets-build.ts; do not edit.\nexport const STUDIO_SKILL_ASSETS = {\n${entries.sort().join("\n")}\n};\n`;
if (process.argv.includes("--check")) {
	assert.equal(
		readFileSync(output, "utf8"),
		generated,
		"Stale Studio skill assets; run pnpm studio:assets",
	);
} else {
	writeFileSync(output, generated);
}
console.info(`Verified ${entries.length} pinned Studio skill assets`);
